type Lang = "it" | "en"

let current: Lang = (localStorage.getItem("touchline_lang") as Lang) || "it"
const listeners = new Set<() => void>()

export function getLang(): Lang { return current }

export function setLang(lang: Lang) {
  current = lang
  localStorage.setItem("touchline_lang", lang)
  listeners.forEach((fn) => fn())
}

export function toggleLang() {
  setLang(current === "it" ? "en" : "it")
}

export function onLangChange(fn: () => void): () => void {
  listeners.add(fn)
  return () => { listeners.delete(fn) }
}

export function t(key: string, params: Record<string, string> = {}): string {
  let value = dict[current]?.[key] ?? dict.en[key] ?? key
  for (const [k, v] of Object.entries(params)) value = value.replace(`{${k}}`, v)
  return value
}

import { useEffect, useState } from "react"

// Local hook so components re-render when the language changes.
export function useI18n(): void {
  const [, setTick] = useState(0)
  useEffect(() => {
    return onLangChange(() => setTick((n) => n + 1))
  }, [])
}
